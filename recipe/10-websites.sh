#!/bin/bash
# recipe/10-websites.sh — static websites (no PHP), served by nginx.
# Run from your computer:
#   ./nv sh tools/publish-sites.sh                    push each site's content (websites[].source, on your computer)
#   NV_CERT=<site> ./nv run recipe/10-websites.sh     issue that site's cert (then the nginx config below)
#   ./nv run recipe/10-websites.sh                    nginx config for every site that has a cert
# Settings: websites[] with
#   name              the site, e.g. example.org (www.<name> redirects to it)
#   cert              "dns":  DNS-01 with the Cloudflare token from recipe/02 (the token must cover that zone);
#                             works before the site's DNS points here
#                     "http": HTTP-01 through port 80; the site's DNS must already point here
#   source            folder on your computer with the site's files (index.html at the top), for publish-sites.sh
#   webmail_redirect  true: <site>/rc and /rc/... redirect to the webmail (keeps an old webmail path working)
# DNS: A/AAAA records -> the server, not proxied, so the server's own Let's Encrypt cert is what visitors see.
# Certs renew with the others (certbot timer); the deploy hook from recipe/02 reloads nginx.

WEBMAIL=${NV_WEBMAIL_HOSTNAME:-rc.$NV_SERVER_HOSTNAME}
N=${NV_WEBSITES_COUNT:-0}

if [ -n "${NV_CERT:-}" ]; then
  method=""
  for ((i = 0; i < N; i++)); do n=NV_WEBSITES_${i}_NAME; c=NV_WEBSITES_${i}_CERT; [ "${!n}" = "$NV_CERT" ] && method=${!c}; done
  case $method in
    dns)  auth=(--dns-cloudflare --dns-cloudflare-credentials /root/.secrets/cloudflare.ini --dns-cloudflare-propagation-seconds 30) ;;
    http) auth=(--webroot -w /var/www/letsencrypt) ;;
    *)    echo "$NV_CERT: not in websites[] (or no cert method)"; exit 1 ;;
  esac
  certbot certonly --non-interactive --agree-tos --keep-until-expiring "${auth[@]}" --cert-name "$NV_CERT" -d "$NV_CERT" -d "www.$NV_CERT"
fi

echo "== nginx (only sites whose cert exists)"
out=/etc/nginx/conf.d/40-websites.conf
OUT="# Generated by recipe/10-websites.sh — static sites (content: websites[].source, pushed by tools/publish-sites.sh)
"
for ((i = 0; i < N; i++)); do
  n=NV_WEBSITES_${i}_NAME; r=NV_WEBSITES_${i}_WEBMAIL_REDIRECT; site=${!n}
  if live && [ ! -f /etc/letsencrypt/live/$site/fullchain.pem ]; then
    OUT+="# $site: no cert yet (NV_CERT=$site ./nv run recipe/10-websites.sh)
"
    continue
  fi
  extra=""
  # an old webmail path on this site: send bookmarks and left-open tabs to the new one
  [ "${!r:-no}" = yes ] && extra="    location = /rc { return 301 https://$WEBMAIL/; }
    location ^~ /rc/ { return 301 https://$WEBMAIL/; }"
  IFS= read -r -d '' block <<CONF || true
server {
    listen 443 ssl;
    listen [::]:443 ssl;
    http2 on;
    server_name www.$site;
    ssl_certificate     /etc/letsencrypt/live/$site/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/$site/privkey.pem;
    return 301 https://$site\$request_uri;
}
server {
    listen 443 ssl;
    listen [::]:443 ssl;
    http2 on;
    server_name $site;
    ssl_certificate     /etc/letsencrypt/live/$site/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/$site/privkey.pem;
    add_header Strict-Transport-Security "max-age=31536000" always;
    add_header X-Content-Type-Options nosniff always;
    limit_req zone=perip burst=50 nodelay;
    root /var/www/sites/$site;
    index index.html index.htm;
    autoindex off;
$extra
    location ~ /\. { deny all; }
    location / { try_files \$uri \$uri/ =404; }
}
CONF
  OUT+=$block
done
printf '%s' "$OUT" | put $out
nginx -t 2>&1 | tail -1 && systemctl reload nginx
grep -E "^# |server_name" $out
