#!/bin/bash
# recipe/06-mail-domain-certs.sh — TLS for per-domain mail helper hostnames
# (mta-sts., autoconfig., autodiscover., ua-auto-config. for every hosted mail domain).
# These names CNAME to server.hostname, so they can't use the *.<server.hostname> wildcard.
# Issued via HTTP-01 through nginx (port 80 is open): no per-zone Cloudflare token needed.
#
# Add a domain: add it to mail.helper_domains in site.json (after its DNS CNAMEs exist), then re-run:
#   ./nv run recipe/06-mail-domain-certs.sh

read -r -a MAIL_DOMAINS <<< "${NV_MAIL_HELPER_DOMAINS:?set mail.helper_domains in site.json}"
PREFIXES=(mta-sts autoconfig autodiscover ua-auto-config)
WEBROOT=/var/www/letsencrypt
CERT=mail-domains

names=()
for d in "${MAIL_DOMAINS[@]}"; do for p in "${PREFIXES[@]}"; do names+=("$p.$d"); done; done

echo "== ACME webroot on port 80 (before the https redirect)"
mkdir -p $WEBROOT/.well-known/acme-challenge
restorecon -R $WEBROOT 2>/dev/null || true
C10=/etc/nginx/conf.d/10-$NV_SERVER_HOSTNAME.conf
nginx_track "$C10"   # edited below, not via put: restorable too
NGINX_CONF=$C10 python3 - <<'PY'
import os, pathlib, re
p = pathlib.Path(os.environ['NGINX_CONF']); s = p.read_text()
if 'acme-challenge' not in s:
    s = s.replace("""    server_name _;
    return 301 https://$host$request_uri;
}""", """    server_name _;
    location ^~ /.well-known/acme-challenge/ { root /var/www/letsencrypt; }
    location / { return 301 https://$host$request_uri; }
}""", 1)
    p.write_text(s); print("added acme-challenge location")
PY
nginx_apply reload

echo "== issue/expand cert '$CERT' for ${#names[@]} names"
args=(); for n in "${names[@]}"; do args+=(-d "$n"); done
certbot certonly -n --agree-tos --register-unsafely-without-email \
  --webroot -w $WEBROOT --key-type ecdsa --cert-name $CERT --expand "${args[@]}"

echo "== nginx server block for those names -> Stalwart"
LIVE=/etc/letsencrypt/live/$CERT
put /etc/nginx/conf.d/20-mail-domains.conf <<EOF
# Generated by recipe/06-mail-domain-certs.sh — per-domain mail helper names
server {
    listen 443 ssl;
    listen [::]:443 ssl;
    http2 on;
    server_name ${names[*]};
    ssl_certificate     $LIVE/fullchain.pem;
    ssl_certificate_key $LIVE/privkey.pem;
    limit_req zone=perip burst=50 nodelay;
    add_header Strict-Transport-Security "max-age=31536000" always;
    # Only what mail apps and other mail servers ask these names for (Stalwart's routes for them): MTA-STS policy,
    # ua-auto-config, Thunderbird autoconfig, Outlook autodiscover. Anything else (the admin console, the login and
    # token endpoints) is not reachable through these names, so admin.allow and the login rate limit can't be bypassed.
    location = /.well-known/mta-sts.txt                       { proxy_pass http://127.0.0.1:8080; include /etc/nginx/stalwart_proxy.conf; }
    location = /.well-known/user-agent-configuration.json     { proxy_pass http://127.0.0.1:8080; include /etc/nginx/stalwart_proxy.conf; }
    location = /.well-known/autoconfig/mail/config-v1.1.xml   { proxy_pass http://127.0.0.1:8080; include /etc/nginx/stalwart_proxy.conf; }
    location = /mail/config-v1.1.xml                          { proxy_pass http://127.0.0.1:8080; include /etc/nginx/stalwart_proxy.conf; }
    location ~* ^/autodiscover/autodiscover\.(xml|json)       { proxy_pass http://127.0.0.1:8080; include /etc/nginx/stalwart_proxy.conf; }
    location / { return 404; }
}
EOF
nginx_apply reload

echo "== checks"
for d in "${MAIL_DOMAINS[@]}"; do
  printf '%s mta-sts.txt: ' "$d"; curl -s --max-time 10 "https://mta-sts.$d/.well-known/mta-sts.txt" | tr '\n' ' '; echo
  printf '%s autoconfig: ' "$d"; curl -s -o /dev/null -w '%{http_code}\n' --max-time 10 "https://autoconfig.$d/mail/config-v1.1.xml?emailaddress=test@$d"
  printf '%s ua-auto-config: ' "$d"; curl -s -o /dev/null -w '%{http_code}\n' --max-time 10 "https://ua-auto-config.$d/.well-known/user-agent-configuration.json"
  live || continue
  code=$(curl -s -o /dev/null -w '%{http_code}' --max-time 10 "https://autoconfig.$d/admin")
  [ "$code" = 404 ] || { echo "autoconfig.$d/admin answered HTTP $code, expected 404: the helper names must not reach the admin console"; exit 1; }
done
